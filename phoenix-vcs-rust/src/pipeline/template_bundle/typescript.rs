/// Generate package.json using ThPackageJson formal theory
/// 
/// This implements μ_package_json: ThSpec → ThPackageJson → String
pub fn generate_package_json_term(project_name: &str, deps: &[String]) -> String {
    let sanitized_name = project_name.to_lowercase().replace(" ", "-").replace("_", "-");
    
    // Build dependencies object
    let dependencies = if deps.is_empty() {
        "  \"dependencies\": {}".to_string()
    } else {
        let dep_lines: Vec<String> = deps.iter()
            .map(|d| format!("    \"{}\": \"^latest\"", d))
            .collect();
        format!("  \"dependencies\": {{\n{}\n  }}", dep_lines.join(",\n"))
    };
    
    format!(r#"{{
  "name": "{}",
  "version": "0.1.0",
  "description": "Generated by Phoenix VCS formal pipeline",
  "type": "module",
  "scripts": {{
    "dev": "bun run --hot index.ts",
    "start": "bun run index.ts",
    "build": "bun build index.ts --outdir ./dist",
    "typecheck": "tsc --noEmit"
  }},
{},
  "devDependencies": {{
    "@types/bun": "latest",
    "typescript": "^5.3.0"
  }}
}}"#, sanitized_name, dependencies)
}

