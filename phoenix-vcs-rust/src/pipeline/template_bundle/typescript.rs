/// Generate TypeScript-specific files
/// Generate Lit-specific files
pub fn generate_lit_file(
    theory: &FormalTheory,
    project_name: &str,
) -> String {
    match theory {
        FormalTheory::ThLitPackageJson => {
            generate_lit_package_json_term(project_name)
        }
        FormalTheory::ThLitTsConfig => {
            generate_lit_tsconfig_term()
        }
        FormalTheory::ThLitViteConfig => {
            generate_lit_vite_config_term()
        }
        FormalTheory::ThLitHtml => {
            generate_lit_index_html_term(project_name)
        }
        FormalTheory::ThLitMain => {
            generate_lit_main_term(project_name)
        }
        _ => "// Unknown Lit theory".to_string(),
    }
}

/// Generate TypeScript-specific files (Hono or generic)
pub fn generate_typescript_file(
    theory: &FormalTheory,
    project_name: &str,
    _spec_content: &str,
    _ius: &[crate::pipeline::ImplementationUnit],
    _all_deps: &[String],
) -> String {
    match theory {
        FormalTheory::ThTypeScript => {
            generate_hono_server_term(project_name, "")
        }
        FormalTheory::ThPackageJson => {
            generate_package_json_term(project_name, &["hono".to_string()])
        }
        FormalTheory::ThTsConfig => {
            generate_tsconfig_term()
        }
        // Lit theories
        FormalTheory::ThLitPackageJson => {
            generate_lit_package_json_term(project_name)
        }
        FormalTheory::ThLitTsConfig => {
            generate_lit_tsconfig_term()
        }
        FormalTheory::ThLitViteConfig => {
            generate_lit_vite_config_term()
        }
        FormalTheory::ThLitHtml => {
            generate_lit_index_html_term(project_name)
        }
        FormalTheory::ThLitMain => {
            generate_lit_main_term(project_name)
        }
        _ => "// Unknown TypeScript theory".to_string(),
    }
}
