#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn test_generate_elena_app() {
        let config = json!({
            "project_name": "test-elena-app"
        });
        
        let files = generate_elena_app(&config).unwrap();
        
        assert!(files.contains_key("package.json"));
        assert!(files.contains_key("src/main.ts"));
        assert!(files.contains_key("src/server.ts"));
        
        let main_ts = files.get("src/main.ts").unwrap();
        assert!(main_ts.contains("elenajs"));
        assert!(main_ts.contains("hono"));
    }
}
