//! ElenaJS Bundle Generator
//! 
//! Generates TypeScript web applications using ElenaJS framework with Hono backend

use std::collections::HashMap;

/// Generate ElenaJS + Hono application files
pub fn generate_elena_app(config: &serde_json::Value) -> Result<HashMap<String, String>, String> {
    let project_name = config.get("project_name")
        .and_then(|v| v.as_str())
        .unwrap_or("elena-app");
    
    let mut files = HashMap::new();
    
    // Generate package.json
    files.insert("package.json".to_string(), generate_package_json(project_name));
    
    // Generate tsconfig.json
    files.insert("tsconfig.json".to_string(), generate_tsconfig_json());
    
    // Generate vite.config.ts
    files.insert("vite.config.ts".to_string(), generate_vite_config());
    
    // Generate index.html
    files.insert("index.html".to_string(), generate_index_html(project_name));
    
    // Generate server.ts (Hono backend)
    files.insert("src/server.ts".to_string(), generate_server_ts(project_name));
    
    // Generate main.ts (client entry)
    files.insert("src/main.ts".to_string(), generate_main_ts(project_name));
    
    Ok(files)
}

