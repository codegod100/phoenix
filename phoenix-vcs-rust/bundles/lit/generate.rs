/// Generate src/main.ts with configurable components
fn generate_main(project_name: &str, spec_content: &str) -> String {
    let tag = project_name.to_lowercase().replace(" ", "-").replace("_", "-");
    let class_name = to_pascal_case(&tag);
    
    // Parse spec for component configuration
    let config = parse_spec_config(spec_content);
    
    let mut main_ts = String::new();
    
    // Header
    main_ts.push_str(&format!("// phoenix: iu_id = \"{}-app\"\n", tag));
    main_ts.push_str(&format!("// Generated by Phoenix VCS for {}\n\n", project_name));
    main_ts.push_str("import { LitElement, html, css } from 'lit';\n");
    main_ts.push_str("import { customElement, property } from 'lit/decorators.js';\n\n");
    
    // Hero component (if enabled)
    if config.has_hero {
        main_ts.push_str(&generate_hero_component(&config.hero_message, &config.hero_subtitle));
        main_ts.push_str("\n");
    }
    
    // Counter component
    if config.has_counter {
        main_ts.push_str(&generate_counter_component());
        main_ts.push_str("\n");
    }
    
    // Todo list component
    if config.has_todo {
        main_ts.push_str(&generate_todo_component());
        main_ts.push_str("\n");
    }
    
    // Main app component
    main_ts.push_str(&generate_app_component(&tag, &class_name, &config));
    main_ts.push_str("\n");
    main_ts.push_str(&format!("console.log('🔥 {} app loaded');\n", project_name));
    
    main_ts
}

/// Configuration parsed from spec
struct ComponentConfig {
    has_hero: bool,
    hero_message: String,
    hero_subtitle: String,
    has_counter: bool,
    has_todo: bool,
}

impl Default for ComponentConfig {
    fn default() -> Self {
        Self {
            has_hero: true,
            hero_message: "Hello World".to_string(),
            hero_subtitle: "Welcome".to_string(),
            has_counter: true,
            has_todo: false,
        }
    }
}

/// Parse component configuration from spec content
fn parse_spec_config(spec_content: &str) -> ComponentConfig {
    let mut config = ComponentConfig::default();
    let content_lower = spec_content.to_lowercase();
    
    // Check for hero
    config.has_hero = content_lower.contains("hero");
    
    // Check for counter
    config.has_counter = content_lower.contains("counter");
    
    // Check for todo
    config.has_todo = content_lower.contains("todo");
    
    // Try to extract hero message
    if let Some(msg) = extract_hero_message(spec_content) {
        config.hero_message = msg;
    }
    
    config
}

/// Extract hero message from spec
fn extract_hero_message(spec_content: &str) -> Option<String> {
    // Look for patterns like "message = \"Hello World\"" or similar
    for line in spec_content.lines() {
        let line_lower = line.to_lowercase();
        if line_lower.contains("hero") && line_lower.contains("message") {
            // Try to extract quoted string
            if let Some(start) = line.find('"') {
                let rest = &line[start + 1..];
                if let Some(end) = rest.find('"') {
                    return Some(rest[..end].to_string());
                }
            }
        }
    }
    None
}

/// Convert kebab-case to PascalCase
fn to_pascal_case(s: &str) -> String {
    s.split('-')
        .map(|p| {
            let mut chars = p.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => c.to_uppercase().collect::<String>() + &chars.as_str().to_lowercase(),
            }
        })
        .collect()
}

