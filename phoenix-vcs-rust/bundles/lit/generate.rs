use std::collections::HashMap;
use std::path::PathBuf;

/// Generate all files for the Lit bundle
pub fn generate(project_name: &str, spec_content: &str) -> HashMap<PathBuf, String> {
    let mut files = HashMap::new();
    
    files.insert(PathBuf::from("package.json"), generate_package_json(project_name));
    files.insert(PathBuf::from("tsconfig.json"), generate_tsconfig());
    files.insert(PathBuf::from("vite.config.ts"), generate_vite_config());
    files.insert(PathBuf::from("index.html"), generate_index_html(project_name));
    files.insert(PathBuf::from("src/main.ts"), generate_main(project_name, spec_content));
    
    files
}

